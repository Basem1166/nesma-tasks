import { useEffect, useRef, useState, type FormEvent } from 'react'
import { api, errorText } from '../api'
import { ErrorBox, Markdown, Spinner } from '../components/ui'
import { relTime, useApi } from '../hooks'
import { useUser } from '../session'

interface AiMessage {
  id: string
  role: 'user' | 'assistant'
  text: string
  toolsUsed: string[]
}

const TOOL_LABEL: Record<string, string> = {
  search_tasks: 'searched tasks',
  get_task: 'read task details',
  get_team_overview: 'checked team overview',
  get_period_metrics: 'computed metrics',
  list_team_members: 'listed members',
  get_recent_activity: 'read recent activity',
}

const LEADER_PROMPTS = [
  'What is overdue right now and who owns it?',
  'Summarise team progress this month',
  'Who has the heaviest workload?',
  'Compare October with September',
]
const MEMBER_PROMPTS = ['What should I work on first today?', 'Summarise my progress this week', 'Which of my tasks are at risk?']

export function Assistant() {
  const user = useUser()
  const status = useApi<{ configured: boolean; model: string }>('/ai/status')
  const convs = useApi<{ conversations: { id: string; title: string; updatedAt: string }[] }>('/ai/conversations')
  const [conversationId, setConversationId] = useState<string | null>(null)
  const [messages, setMessages] = useState<AiMessage[]>([])
  const [input, setInput] = useState('')
  const [thinking, setThinking] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const bottom = useRef<HTMLDivElement>(null)

  useEffect(() => {
    bottom.current?.scrollIntoView({ block: 'end', behavior: 'smooth' })
  }, [messages, thinking])

  const open = async (id: string) => {
    setConversationId(id)
    setError(null)
    const t = await api<{ messages: AiMessage[] }>(`/ai/conversations/${id}`)
    setMessages(t.messages)
  }

  const ask = async (text: string) => {
    if (!text.trim() || thinking) return
    setError(null)
    setInput('')
    const pending: AiMessage = { id: `tmp-${Date.now()}`, role: 'user', text, toolsUsed: [] }
    setMessages((m) => [...m, pending])
    setThinking(true)
    try {
      const r = await api<{ conversationId: string; reply: string; toolsUsed: string[] }>('/ai/chat', {
        method: 'POST',
        json: { message: text, conversationId: conversationId ?? undefined },
      })
      setConversationId(r.conversationId)
      setMessages((m) => [...m, { id: `a-${Date.now()}`, role: 'assistant', text: r.reply, toolsUsed: r.toolsUsed }])
      void convs.reload()
    } catch (e) {
      setError(errorText(e))
      setMessages((m) => m.filter((x) => x.id !== pending.id))
      setInput(text)
    } finally {
      setThinking(false)
    }
  }

  const submit = (e: FormEvent) => {
    e.preventDefault()
    void ask(input)
  }

  const remove = async (id: string) => {
    await api(`/ai/conversations/${id}`, { method: 'DELETE' })
    if (id === conversationId) newChat()
    void convs.reload()
  }

  const newChat = () => {
    setConversationId(null)
    setMessages([])
    setError(null)
  }

  const prompts = user.role === 'LEADER' ? LEADER_PROMPTS : MEMBER_PROMPTS

  return (
    <>
      <div className="page-head">
        <div>
          <h1>AI assistant</h1>
          <p>Ask about tasks, progress and performance. Answers are generated by AI{status.data?.configured ? ` (${status.data.model})` : ''} from live team data you're allowed to see.</p>
        </div>
        <button className="btn" onClick={newChat}>+ New chat</button>
      </div>
      {status.data && !status.data.configured && (
        <div className="alert warn" style={{ marginBottom: 12 }}>
          AI is not configured on the server. Put a free Gemini key in <code>AI_API_KEY</code> in <code>server/.env</code> and restart (see docs/SETUP.md).
        </div>
      )}
      <div className="card ai">
        <div className="chat-list">
          {convs.data?.conversations.map((c) => (
            <div key={c.id} className="row" style={{ borderBottom: '1px solid var(--border)', background: c.id === conversationId ? 'var(--brand-soft)' : undefined }}>
              <button style={{ borderBottom: 'none', flex: 1, minWidth: 0 }} onClick={() => open(c.id)}>
                <div style={{ fontWeight: 550, overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>{c.title}</div>
                <div className="small muted">{relTime(c.updatedAt)}</div>
              </button>
              <button className="icon-btn" style={{ width: 'auto' }} aria-label="Delete conversation" onClick={() => remove(c.id)}>✕</button>
            </div>
          ))}
          {convs.data?.conversations.length === 0 && <div className="empty small">No conversations yet</div>}
        </div>
        <div className="chat-pane">
          <div className="chat-msgs">
            {messages.length === 0 && !thinking && (
              <div style={{ margin: 'auto', textAlign: 'center', maxWidth: 520 }}>
                <div style={{ fontSize: 34 }}>✦</div>
                <h2>How can I help, {user.name.split(' ')[0]}?</h2>
                <p className="secondary small" style={{ marginTop: 6 }}>
                  {user.role === 'LEADER' ? 'I can see every task in your team.' : 'I can see the tasks assigned to you or created by you.'}
                </p>
                <div className="suggestions">
                  {prompts.map((p) => <button key={p} onClick={() => ask(p)}>{p}</button>)}
                </div>
              </div>
            )}
            {messages.map((m) =>
              m.role === 'user' ? (
                <div key={m.id} className="ai-msg user">{m.text}</div>
              ) : (
                <div key={m.id} className="ai-msg assistant">
                  {m.toolsUsed.length > 0 && (
                    <div className="row wrap small muted" style={{ marginBottom: 6, gap: 6 }}>
                      {m.toolsUsed.map((t) => <span key={t} className="badge">🔎 {TOOL_LABEL[t] ?? t}</span>)}
                    </div>
                  )}
                  <Markdown>{m.text}</Markdown>
                </div>
              ),
            )}
            {thinking && <div className="row secondary small"><Spinner /> Analysing team data…</div>}
            <div ref={bottom} />
          </div>
          <div style={{ padding: '0 12px' }}><ErrorBox error={error} /></div>
          <form className="chat-input" onSubmit={submit}>
            <input className="input" placeholder="Ask about tasks, deadlines, workload…" value={input} onChange={(e) => setInput(e.target.value)} disabled={thinking} maxLength={4000} />
            <button className="btn primary" disabled={thinking || !input.trim()}>Ask</button>
          </form>
        </div>
      </div>
    </>
  )
}
